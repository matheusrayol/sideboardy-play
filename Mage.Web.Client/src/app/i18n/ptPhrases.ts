export function translatePtPhrase(text: string): string {
  if (!text) return text;
  const hit = EXACT[text];
  if (hit !== undefined) return hit;
  for (const [pattern, formatter] of RULES) {
    const match = pattern.exec(text);
    if (match) return formatter(...match);
  }
  return text;
}
